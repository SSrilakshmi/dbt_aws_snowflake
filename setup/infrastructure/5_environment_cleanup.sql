FOR i IN 0 TO ARRAY_SIZE(:arr_databases) - 1 DO
    EXECUTE IMMEDIATE 'DROP DATABASE IF EXISTS ' || :arr_databases[i];
END FOR;

END;

DELETE FROM DB_AIRBNB_RAW.STAGING.BOOKINGS;
