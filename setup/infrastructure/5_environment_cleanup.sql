-- Delete duplicate rows if any exist in the staging.listings table based on booking_id and listing_id, keeping only the first occurrence based on filename ordering.

DELETE FROM db_airbnb_raw.staging.listings
WHERE (booking_id, listing_id) IN (
    SELECT booking_id, listing_id
    FROM (
        SELECT listing_id, booking_id, filename, ROW_NUMBER() OVER (PARTITION BY booking_id,  listing_id ORDER BY filename) AS rn
        FROM db_airbnb_raw.staging.bookings
    )
    WHERE rn = 2
);
